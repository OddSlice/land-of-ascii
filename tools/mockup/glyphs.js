// The shape-matching table: for every pattern of sx*sy two-colour samples in a cell, the glyph
// (from a list) whose coverage of each sample's footprint best matches it, allowing the glyph to be
// drawn inverted (fg and bg swapped). Entries are (glyph index << 1) | inverted.
export function buildShapeLUT(glyphs, w, h, sx, sy, penalty = () => 0) {
  const n = sx * sy, cov = glyphs.map(g => {
    const c = new Float32Array(n);
    for (let j = 0; j < sy; j++) for (let i = 0; i < sx; i++) {
      let s = 0, cnt = 0;
      for (let y = Math.floor(j * h / sy); y < Math.floor((j + 1) * h / sy); y++) for (let x = Math.floor(i * w / sx); x < Math.floor((i + 1) * w / sx); x++) { s += g.m[y * w + x]; cnt++; }
      c[j * sx + i] = s / cnt;
    }
    return c;
  });
  const lut = new Uint16Array(1 << n), err = new Float32Array(1 << n);
  for (let p = 0; p < 1 << n; p++) {
    let best = 1e9, bi = 0;
    for (let g = 0; g < glyphs.length; g++) {
      const c = cov[g];
      let e0 = 0, e1 = 0;
      for (let k = 0; k < n; k++) { const b = (p >> k) & 1; e0 += (c[k] - b) ** 2; e1 += (1 - c[k] - b) ** 2; }
      const pen = penalty(glyphs[g]);
      if (e0 + pen < best) { best = e0 + pen; bi = g << 1; }
      if (e1 + pen < best) { best = e1 + pen; bi = (g << 1) | 1; }
    }
    lut[p] = bi; err[p] = best;
  }
  return { lut, err };
}

export function dedupe(list) {
  const seen = new Set(), out = [];
  for (const g of list) { const k1 = key(g.m), k2 = key(invert(g.m)); if (seen.has(k1) || seen.has(k2)) continue; seen.add(k1); out.push(g); }
  return out;
}
