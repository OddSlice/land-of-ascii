// Glyphs are bitmasks the size of a cell, built by hand or by formula, never trusted to a font:
// a system font's block characters rasterise solid at small sizes and differ per browser.
// Every candidate draws from the same machinery: a glyph is a Uint8Array(w*h) of 0/1.

export function mask(w, h, fn) { const m = new Uint8Array(w * h); for (let y = 0; y < h; y++) for (let x = 0; x < w; x++) m[y * w + x] = fn(x, y) ? 1 : 0; return m; }
export const coverage = m => { let s = 0; for (let i = 0; i < m.length; i++) s += m[i]; return s / m.length; };
export const invert = m => m.map(v => 1 - v);
export const orMask = (a, b) => a.map((v, i) => v | b[i]);
const key = m => m.join('');

// ---- procedural families ----------------------------------------------------------------------
export function blockFamilies(w, h) {
  const out = [];
  const add = (name, m, fam) => out.push({ name, m, fam });
  add('space', mask(w, h, () => 0), 'basic');
  add('full', mask(w, h, () => 1), 'basic');
  for (let k = 1; k < h; k++) add(`lower${k}/${h}`, mask(w, h, (x, y) => y >= h - k), 'hsplit');
  for (let k = 1; k < w; k++) add(`left${k}/${w}`, mask(w, h, x => x < k), 'vsplit');
  const grid = (cols, rows, fam) => {
    for (let p = 0; p < 1 << (cols * rows); p++) add(`${fam}${p}`, mask(w, h, (x, y) => {
      const cx = Math.min(cols - 1, Math.floor(x * cols / w)), cy = Math.min(rows - 1, Math.floor(y * rows / h));
      return (p >> (cy * cols + cx)) & 1;
    }), fam);
  };
  grid(2, 2, 'quad');
  grid(2, 3, 'sextant');
  grid(2, 4, 'octant');
  // Wedges: the cell cut by a straight line between two points on its border ("smooth mosaics").
  const pts = [];
  for (let k = 0; k <= 6; k++) { pts.push([0, k * h / 6]); pts.push([w, k * h / 6]); }
  for (let k = 1; k < 4; k++) { pts.push([k * w / 4, 0]); pts.push([k * w / 4, h]); }
  for (let a = 0; a < pts.length; a++) for (let b = a + 1; b < pts.length; b++) {
    const [x0, y0] = pts[a], [x1, y1] = pts[b];
    if ((x0 === x1 && (x0 === 0 || x0 === w)) || (y0 === y1 && (y0 === 0 || y0 === h))) continue;   // same edge
    add(`wedge${a}-${b}`, mask(w, h, (x, y) => (x1 - x0) * (y + 0.5 - y0) - (y1 - y0) * (x + 0.5 - x0) > 0), 'wedge');
  }
  return out;
}

// Thin strokes placed where the world says they are (mortar, planks, trunks, staffs).
export const hline = (w, h, row, t = 1) => mask(w, h, (x, y) => y >= row && y < row + t);
export const vline = (w, h, col, t = 1) => mask(w, h, x => x >= col && x < col + t);
// Ordered shade patterns (hand-built, so they never rasterise solid): 1/4, 1/2, 3/4.
export const shade = (w, h, level) => {
  const quarter = (x, y) => y % 2 === 0 && (x + (y >> 1)) % 2 === 0;   // a diagonal lattice of single dots
  return mask(w, h, (x, y) => level === 1 ? quarter(x, y) : level === 2 ? ((x + y) & 1) === 0 : !quarter(x, y));
};

// ---- hand-drawn glyphs ------------------------------------------------------------------------
export function parse(rows) { const h = rows.length, w = rows[0].length; return mask(w, h, (x, y) => rows[y][x] === '#'); }

